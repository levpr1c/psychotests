def get_eysenck_interpretation(e_score: int, n_score: int, l_score: int) -> str:
    lines = ["[bold]Результаты теста Айзенка (EPI)[/bold]", ""]

    for table, score, label in [
        (EYSENCK_EXTRAVERSION, e_score, "Экстраверсия"),
        (EYSENCK_NEUROTICISM, n_score, "Нейротизм"),
        (EYSENCK_LIE, l_score, "Шкала лжи"),
    ]:
        text = ""
        for (lo, hi), desc in table.items():
            if lo <= score <= hi:
                text = desc
                break
        lines.append(f"[bold]{label} ({score} баллов):[/bold] {text}")
        lines.append("")

    lines.append("─" * 20)
    lines.append(f"[bold]Темперамент:[/bold] {_get_temperament(e_score, n_score)}")

    return "\n".join(lines)


def _get_temperament(e: int, n: int) -> str:
    if n <= 12:
        if e <= 12:
            return "Флегматик (стабильный интроверт)"
        else:
            return "Сангвиник (стабильный экстраверт)"
    else:
        if e <= 12:
            return "Меланхолик (нейротичный интроверт)"
        else:
            return "Холерик (нейротичный экстраверт)"


def get_stress_interpretation(score: int) -> str:
    if score <= 30:
        return "Низкий уровень стресса. Вы хорошо справляетесь с нагрузками."
    elif score <= 50:
        return "Умеренный стресс. В целом справляетесь, но стоит уделять внимание отдыху."
    elif score <= 70:
        return "Повышенный стресс. Рекомендуется снизить нагрузку и освоить техники релаксации."
    elif score <= 90:
        return "Высокий стресс. Необходим полноценный отдых и, возможно, консультация специалиста."
    else:
        return "Критический уровень стресса. Настоятельно рекомендуется обратиться к психологу."


